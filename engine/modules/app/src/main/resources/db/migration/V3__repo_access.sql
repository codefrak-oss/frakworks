-- Who may start which flow on a target repo, by labelling an issue with the
-- flow's name (engine/README.md, "Starting a flow from an issue").
CREATE TABLE engine.repo_access (
    full_name  VARCHAR(200) NOT NULL REFERENCES engine.target_repo (full_name) ON DELETE CASCADE,
    flow       VARCHAR(40)  NOT NULL,   -- also the trigger label: chore
    login      VARCHAR(100) NOT NULL,   -- a GitHub login
    PRIMARY KEY (full_name, flow, login)
);

-- Every grant and revoke, kept: repo_access only says what is true now.
CREATE TABLE engine.repo_access_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change      VARCHAR(10)  NOT NULL,  -- grant | revoke
    full_name   VARCHAR(200) NOT NULL,
    flow        VARCHAR(40)  NOT NULL,
    login       VARCHAR(100) NOT NULL,
    changed_by  VARCHAR(100)            -- who asked, as they said; unverified until the API is authenticated
);
