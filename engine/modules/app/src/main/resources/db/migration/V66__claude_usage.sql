-- The consumption ledger (#1934; engine/README.md, "Consumption ledger"): one row per Claude consumer event, a
-- Smith run at `collect result` or one of the engine's own direct calls (the summarizer, the usage-refresh probe,
-- credential verification). `caller` is smith-run, doctor, refactor-scan, job, summarizer, usage-probe or
-- credential-verify; `role` is a smith-run's timeline role (`coding` for mode `work`, `correctness` for `review`), null otherwise. A figure the engine does
-- not know is null, never 0: a direct call has no cost (no price table, #1009), a run with no closing result none either.
CREATE TABLE engine.claude_usage (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller      VARCHAR(40)              NOT NULL,
    role        VARCHAR(40),
    run_id      VARCHAR(64),
    repo        VARCHAR(200),
    issue       BIGINT,
    account     VARCHAR(100),
    model       VARCHAR(100),
    started     TIMESTAMP WITH TIME ZONE,
    ended       TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms BIGINT,
    cost_usd    DOUBLE PRECISION,
    input_tokens       BIGINT,
    output_tokens      BIGINT,
    cache_read_tokens  BIGINT,
    cache_write_tokens BIGINT
);
CREATE INDEX claude_usage_ended ON engine.claude_usage (ended);
