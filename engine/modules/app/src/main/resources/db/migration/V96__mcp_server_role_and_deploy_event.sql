-- The ops role on a repo MCP server (#100008; engine/docs/feature.md, "First mate's MCP servers", "The ops role"): a
-- row with role 'ops' conforms to the ops/1 contract (a tool is_deployed(sha) answering {state: deployed|not_yet}), and
-- DeployedChecks asks it whether a commit is in production for the repo. Existing rows carry no role.
ALTER TABLE engine.repo_mcp_server ADD COLUMN role VARCHAR(20) NULL CHECK (role IN ('ops'));

-- A deploy of a target repo the engine was told of (POST /repos/{owner}/{name}/deploys, or its own start for its build
-- repo): the commit now in production and who said so. Read by GET .../deploys, newest first.
CREATE TABLE engine.deploy_event (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo   VARCHAR(200)             NOT NULL REFERENCES engine.target_repo (full_name) ON DELETE CASCADE,
    sha    VARCHAR(40)              NOT NULL,
    source VARCHAR(100),
    at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX deploy_event_repo_at ON engine.deploy_event (repo, at DESC);
