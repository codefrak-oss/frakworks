-- Engine-wide grants: a login granted a kind here holds it on every target
-- repo, current and future (engine/README.md, "Starting a flow from an issue").
-- flow '*' is every grant kind, the ones added later too.
CREATE TABLE engine.engine_access (
    flow        VARCHAR(40)  NOT NULL,  -- a grant kind, or '*'
    login       VARCHAR(100) NOT NULL,  -- a GitHub login
    granted_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (flow, login)
);

-- Every engine-wide grant and revoke, kept.
CREATE TABLE engine.engine_access_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change      VARCHAR(10)  NOT NULL,  -- grant | revoke
    flow        VARCHAR(40)  NOT NULL,
    login       VARCHAR(100) NOT NULL,
    changed_by  VARCHAR(100)            -- who asked, as they said; unverified
);
