-- The engine's leader lease (#1672; engine/README.md, "Replicas and the lease"): one row, the instance that runs the
-- singleton work (schedulers, job executor, Smith log following) and until when. EngineLease takes it with a
-- conditional UPDATE when it is free, expired or already its own; a graceful stop sets holder back to NULL.
CREATE TABLE engine.engine_lease (
    name         VARCHAR(40)  PRIMARY KEY,
    holder       VARCHAR(253),                        -- the instance id (the hostname, a pod's name); null: free
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    heartbeat_at TIMESTAMP WITH TIME ZONE
);
INSERT INTO engine.engine_lease (name, holder, expires_at) VALUES ('engine', NULL, TIMESTAMP WITH TIME ZONE '1970-01-01 00:00:00+00');

-- An event frame too large for a Postgres NOTIFY payload (8000 bytes), for the other replicas to read by id
-- (PostgresEventRelay). The sender deletes rows older than a minute as it adds one.
CREATE TABLE engine.event_relay (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin VARCHAR(253)             NOT NULL,
    repo   VARCHAR(200)             NOT NULL,
    frame  TEXT                     NOT NULL,
    at     TIMESTAMP WITH TIME ZONE NOT NULL
);
