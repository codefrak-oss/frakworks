package com.codefrak.engine.events

import com.codefrak.engine.lease.InstanceId
import org.junit.jupiter.api.Test
import org.springframework.jdbc.core.JdbcTemplate
import org.springframework.jdbc.datasource.SingleConnectionDataSource
import tools.jackson.module.kotlin.jacksonObjectMapper
import java.time.Duration
import java.time.Instant
import java.time.OffsetDateTime
import java.time.ZoneOffset
import java.util.UUID
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * The event relay between two replicas (engine/README.md, "Replicas and the lease"), driven by a fake listener: H2 has
 * no LISTEN/NOTIFY, so a payload engine-a would NOTIFY is handed to [PostgresEventRelay.receive] on engine-b by hand.
 * An event published on A reaches B's SSE subscribers once; B skips what it sent itself; a frame too large for a
 * NOTIFY payload is read back from `engine.event_relay` by id.
 */
class PostgresEventRelayTest {
    private val json = jacksonObjectMapper()
    private val template = JdbcTemplate(SingleConnectionDataSource("jdbc:h2:mem:relay-${UUID.randomUUID()}", "sa", "", true)).apply {
        execute("CREATE SCHEMA engine")
        execute("""CREATE TABLE engine.event_relay (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, origin VARCHAR(253) NOT NULL,
            repo VARCHAR(200) NOT NULL, frame TEXT NOT NULL, at TIMESTAMP WITH TIME ZONE NOT NULL)""")
    }
    private fun relay(name: String) = PostgresEventRelay(template, InstanceId(name), json, "jdbc:none", "", "")
    private val none = Duration.ZERO
    private val at = Instant.parse("2026-10-08T10:00:00Z")

    @Test
    fun `a foreign frame reaches the subscribers on this instance, and its own is skipped`() {
        val b = relay("engine-b")
        val busB = EngineEvents(json, b)
        val sub = busB.subscribe("acme/widgets")
        val frame = busB.frame("ticket", """{"repo":"acme/widgets","number":7}""")

        b.receive(json.writeValueAsString(mapOf("o" to "engine-a", "r" to "acme/widgets", "f" to frame)))
        assertEquals(frame, sub.next(none))
        b.receive(json.writeValueAsString(mapOf("o" to "engine-b", "r" to "acme/widgets", "f" to frame)))
        assertNull(sub.next(none), "its own notification is not delivered twice")
        b.receive(json.writeValueAsString(mapOf("o" to "engine-a", "r" to "acme/other", "f" to frame)))
        assertNull(sub.next(none), "the repo filter holds for relayed frames")
    }

    @Test
    fun `an event published on one bus is delivered locally once and handed to the relay`() {
        val sent = mutableListOf<Pair<String, String>>()
        val relay = object : EventRelay {
            override fun send(repo: String, frame: String) { sent += repo to frame }
            override fun listen(handler: (String, String) -> Unit) {}
            override fun listening() = true
        }
        val bus = EngineEvents(json, relay)
        val sub = bus.subscribe(EngineEvent.FLEET)
        bus.publish(EngineEvent.Ticket("acme/widgets", 7, "labeled", at = at))
        val frame = sub.next(none)!!
        assertNull(sub.next(none))
        assertEquals(listOf("acme/widgets" to frame), sent)
    }

    @Test
    fun `a frame too large for a payload is read from the table by its id`() {
        val b = relay("engine-b")
        val busB = EngineEvents(json, b)
        val sub = busB.subscribe("acme/widgets")
        val big = busB.frame("ticket", "\"" + "x".repeat(PostgresEventRelay.MAX_PAYLOAD) + "\"")
        val id = template.queryForObject("SELECT id FROM FINAL TABLE (INSERT INTO engine.event_relay (origin, repo, frame, at) VALUES (?, ?, ?, ?))",
            Long::class.java, "engine-a", "acme/widgets", big, OffsetDateTime.now(ZoneOffset.UTC))
        b.receive(json.writeValueAsString(mapOf("o" to "engine-a", "id" to id)))
        val got = sub.next(none)
        assertTrue(got == big, "the stored frame, whole")
    }
}
